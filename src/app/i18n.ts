export type MessageKey = keyof typeof chineseMessages;
export type MessageValues = Readonly<Record<string, string | number>>;
export type Translator = (key: MessageKey, values?: MessageValues) => string;

export function createTranslator(language: Language): Translator {
  return (key, values = {}) => (language === "zh-CN" ? chineseMessages[key] : key)
    .replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

export class LocalizedError extends Error {
  constructor(readonly key: MessageKey, readonly values: MessageValues = {}) {
    super(createTranslator("en")(key, values));
  }
}

export function translateError(error: unknown, translate: Translator, fallback: MessageKey): string {
  return error instanceof LocalizedError ? translate(error.key, error.values) : translate(fallback);
}
